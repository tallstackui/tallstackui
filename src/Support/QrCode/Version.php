    /** Two bit indicator written into the format information, per level. */
    private const INDICATORS = ['L' => 0b01, 'M' => 0b00, 'Q' => 0b11, 'H' => 0b10];

    public static function alignments(int $version): array
    {
        $centres = self::ALIGNMENTS[$version];

        if ($centres === []) {
            return [];
        }

        $last = count($centres) - 1;
        $coordinates = [];

        foreach ($centres as $row => $y) {
            foreach ($centres as $column => $x) {
                $corner = ($row === 0 && $column === 0)
                    || ($row === 0 && $column === $last)
                    || ($row === $last && $column === 0);

                if (! $corner) {
                    $coordinates[] = [$x, $y];
                }
            }
        }

        return $coordinates;
    }

    /** Layout of a version and level as [check codewords, [data codewords per block, ...]]. */
    public static function blocks(int $version, string $level): array
    {
        [$check, $first, $data] = self::BLOCKS[$version][$level];

        $sizes = array_fill(0, $first, $data);

        if (isset(self::BLOCKS[$version][$level][3])) {
            [, , , $second, $extra] = self::BLOCKS[$version][$level];

            $sizes = array_merge($sizes, array_fill(0, $second, $extra));
        }

        return [$check, $sizes];
    }

    public static function capacity(int $version, string $level): int
    {
        [, $sizes] = self::blocks($version, $level);

        return array_sum($sizes);
    }

    public static function indicator(string $level): int
    {
        return self::INDICATORS[$level];
    }

    public static function size(int $version): int
    {
        return 17 + 4 * $version;
    }

    /**
     * The character count indicator widens at version ten, so the required
     * length is re-checked against each candidate instead of computed once.
     */
    public static function smallest(int $length, string $level): ?int
    {
        for ($version = 1; $version <= 40; $version++) {
            $required = 4 + Bitstream::counter($version) + $length * 8;

            if ($required <= self::capacity($version, $level) * 8) {
                return $version;
            }
        }

        return null;
    }
